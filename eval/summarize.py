"""Collect every result in eval/results into one table: eval/results/SUMMARY.md.

Usage: python eval/summarize.py
"""

from __future__ import annotations

import json
from pathlib import Path

RESULTS = Path(__file__).parent / "results"
COLUMNS = [
    "Request", "Method", "n", "TP", "FP", "FN", "TN", "Precision", "Recall", "F1",
    "F1 without ambiguous", "s/case",
]


def fmt(value) -> str:
    if value is None:
        return "n/a"
    return f"{value:.2f}" if isinstance(value, float) else str(value)


def row(request: str, method: str, s: dict, clear: dict | None, latency) -> str:
    cells = [
        request, method, s["n"], s["tp"], s["fp"], s["fn"], s["tn"],
        s["precision"], s["recall"], s["f1"], clear["f1"] if clear else None, latency,
    ]
    return "| " + " | ".join(fmt(cell) for cell in cells) + " |"


def main() -> None:
    lines = [
        "# Evaluation summary",
        "",
        "Generated by `eval/summarize.py`. YES is the positive class.",
        "",
        "| " + " | ".join(COLUMNS) + " |",
        "|" + "---|" * len(COLUMNS),
    ]
    for path in sorted(RESULTS.glob("*.classify.*.metrics.json")):
        m = json.loads(path.read_text())
        method = "LLM, prompt " + m["classifier"].split(":")[-1].replace("classify.", "")
        lines.append(
            row(m["request_id"], method, m["all_cases"], m["excluding_ambiguous"],
                m["mean_latency_s"])
        )
    for path in sorted(RESULTS.glob("*.embedding.metrics.json")):
        m = json.loads(path.read_text())
        latency = m["mean_embedding_latency_s"]
        lines.append(row(m["request_id"], "Embedding + logistic regression", m["logreg"], None,
                         latency))
        lines.append(row(m["request_id"], "Embedding similarity threshold", m["similarity"], None,
                         latency))
    text = "\n".join(lines) + "\n"
    (RESULTS / "SUMMARY.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
